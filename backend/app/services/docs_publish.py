SITE_ROOT = Path.home() / "Public" / "doc-sites" / "udos-docs"
STATUS_FILE = "publish.json"

SITE_TITLE = "uDos Documentation"
SITE_DESCRIPTION = "Component documentation for the uDos ecosystem, mirrored from in-repo docs/ directories."


# ─── Markdown rendering (stdlib only) ─────────────────────────────

_INLINE = (
    (re.compile(r"\*\*(.+?)\*\*"), r"<strong>\1</strong>"),
    (re.compile(r"`([^`\n]+)`"), r"<code>\1</code>"),
    (re.compile(r"\*([^*\n]+)\*"), r"<em>\1</em>"),
    (re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)"), r'<a href="\2">\1</a>'),
)


def _inline(text: str) -> str:
    for pattern, repl in _INLINE:
        text = pattern.sub(repl, text)
    return text


def markdown_to_html(md: str) -> str:
    """Render a small, safe subset of Markdown to HTML."""
    lines = md.split("\n")
    out: list[str] = []
    in_code = False
    code_buf: list[str] = []
    list_buf: list[str] = []
    para_buf: list[str] = []

    def flush_para() -> None:
        nonlocal para_buf
        if para_buf:
            out.append("<p>" + " ".join(_inline(p) for p in para_buf) + "</p>")
            para_buf = []

    def flush_list() -> None:
        nonlocal list_buf
        if list_buf:
            out.append("<ul>" + "".join(f"<li>{_inline(i)}</li>" for i in list_buf) + "</ul>")
            list_buf = []

    for line in lines:
        if line.strip().startswith("```"):
            flush_para()
            flush_list()
            if in_code:
                out.append("<pre><code>" + html.escape("\n".join(code_buf)) + "</code></pre>")
                code_buf = []
            in_code = not in_code
            continue
        if in_code:
            code_buf.append(line)
            continue

        stripped = line.strip()
        if not stripped:
            flush_para()
            flush_list()
            continue

        heading = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading:
            flush_para()
            flush_list()
            level = len(heading.group(1))
            out.append(f"<h{level}>{_inline(heading.group(2))}</h{level}>")
            continue

        if re.match(r"^[-*+]\s+", stripped):
            flush_para()
            list_buf.append(stripped[2:].strip())
            continue

        if stripped.startswith("&gt; ") or stripped.startswith("> "):
            flush_para()
            flush_list()
            out.append(f"<blockquote>{_inline(stripped[2:].strip())}</blockquote>")
            continue

        para_buf.append(line.strip())

    flush_para()
    flush_list()
    if in_code and code_buf:
        out.append("<pre><code>" + html.escape("\n".join(code_buf)) + "</code></pre>")
    return "\n".join(out)


# ─── Static site generation ───────────────────────────────────────

def _page(title: str, body: str, crumb: str = "") -> str:
    header = (
        '<header class="site-header">'
        f'<a class="site-home" href="/udos-docs/">uDos Docs</a>'
        f"<span class=\"site-crumb\">{html.escape(crumb)}</span>"
        "</header>"
    )
    return (
        "<!DOCTYPE html><html lang=\"en\"><head>"
        f"<meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
        f"<title>{html.escape(title)} — {html.escape(SITE_TITLE)}</title>"
        '<link rel="stylesheet" href="/udos-docs/assets/style.css">'
        "</head><body>"
        f"{header}<main class=\"site-main\">{body}</main>"
        '<footer class="site-footer">Generated by uCore docs-publish.</footer>'
        "</body></html>"
    )


