def _slug(path: str) -> str:
    return re.sub(r"[^a-zA-Z0-9._/-]+", "-", path)


def build_site(mirror_root: Path | None = None, site_root: Path | None = None) -> dict[str, Any]:
    """Build the static site from the mirror. Returns status summary."""
    mirror = mirror_root or (Path.home() / ".ucore" / "docs-mirror")
    root = site_root or SITE_ROOT

    index_file = mirror / "_mirror.json"
    if not index_file.exists():
        return {"status": "error", "error": f"Mirror index missing: {index_file}"}

    index = json.loads(index_file.read_text(encoding="utf-8"))
    entries = index.get("entries", [])

    docs_dir = root / "docs"
    assets_dir = root / "assets"
    docs_dir.mkdir(parents=True, exist_ok=True)
    assets_dir.mkdir(parents=True, exist_ok=True)

    # Copy raw markdown for each repo.
    by_repo: dict[str, list[dict[str, Any]]] = {}
    for entry in entries:
        repo = entry.get("source_repo", "?")
        by_repo.setdefault(repo, []).append(entry)

    rendered = 0
    for repo, repo_entries in sorted(by_repo.items()):
        repo_dir = docs_dir / repo
        repo_dir.mkdir(parents=True, exist_ok=True)
        repo_rows: list[str] = []
        for entry in sorted(repo_entries, key=lambda e: str(e.get("source_path", "")).lower()):
            src = mirror / entry["mirrored_path"]
            if not src.is_file():
                continue
            rel = entry["source_path"]
            rel_html = rel[:-3] + ".html" if rel.endswith(".md") else rel + ".html"

            # Raw markdown copy.
            dest_md = docs_dir / repo / rel
            dest_md.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest_md)

            # Rendered HTML page.
            content = src.read_text(encoding="utf-8", errors="replace")
            body = markdown_to_html(content)
            page = _page(rel, body, f"{repo} / {rel}")
            dest_html = docs_dir / repo / rel_html
            dest_html.parent.mkdir(parents=True, exist_ok=True)
            dest_html.write_text(page, encoding="utf-8")
            rendered += 1

            repo_rows.append(
                f'<a class="doc-row" href="/udos-docs/docs/{repo}/{_slug(rel_html)}">'
                f"<code>{_slug(rel)}</code>{html.escape(rel)}</a>"
            )

        repo_page = _page(
            f"{repo} — {len(repo_rows)} docs",
            f"<h1>{repo}</h1><p class=\"meta\">{len(repo_rows)} documents</p>" + "\n".join(repo_rows),
            repo,
        )
        (docs_dir / repo / "index.html").write_text(repo_page, encoding="utf-8")

    # Home page.
    repo_cards = []
    for repo, repo_entries in sorted(by_repo.items()):
        repo_cards.append(
            f'<a class="repo-card" href="/udos-docs/docs/{_slug(repo)}/">'
            f"<strong>{html.escape(repo)}</strong>"
            f'<span class="meta"> · {len(repo_entries)} docs</span></a>'
        )
    home = _page(
        SITE_TITLE,
        f"<h1>{SITE_TITLE}</h1><p>{SITE_DESCRIPTION}</p>"
        f'<p class="meta">Mirrored at {index.get("synced_at", "?")} · {len(entries)} files</p>'
        + "\n".join(repo_cards),
    )
    (root / "index.html").write_text(home, encoding="utf-8")

    (assets_dir / "style.css").write_text(_css(), encoding="utf-8")

    # Sitemap.
    sitemap_rows = ["<li><a href=\"/udos-docs/\">Home</a></li>"]
    for repo in sorted(by_repo):
        sitemap_rows.append(f"<li><a href=\"/udos-docs/docs/{_slug(repo)}/\">{html.escape(repo)}</a></li>")
    (root / "sitemap.html").write_text(
        _page("Sitemap", "<h1>Sitemap</h1><ul>" + "".join(sitemap_rows) + "</ul>"),
        encoding="utf-8",
    )

    built_at = datetime.now(UTC).isoformat()
    status = {
        "status": "ok",
        "built_at": built_at,
        "site_root": str(root),
        "total_files": len(entries),
        "rendered_pages": rendered,
        "repos": {repo: len(items) for repo, items in sorted(by_repo.items())},
    }
    (root / STATUS_FILE).write_text(json.dumps(status, indent=2), encoding="utf-8")
    log.info("Docs site built: %d pages at %s", rendered, root)
    return status


def publish_status(site_root: Path | None = None) -> dict[str, Any]:
    """Return the last publish status."""
    root = site_root or SITE_ROOT
    path = root / STATUS_FILE
    if not path.exists():
        return {"status": "not-built", "site_root": str(root)}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {"status": "error", "site_root": str(root)}


def deploy_site(site_root: Path | None = None) -> dict[str, Any]:
    """Deploy the built site via git (commit + push) if it is a git repo."""
    root = site_root or SITE_ROOT
    if not (root / ".git").exists():
        return {"deployed": False, "reason": "site_root is not a git repository"}

    def _run(args: list[str]) -> dict[str, Any]:
        proc = subprocess.run(
            ["git", "-C", str(root), *args],
            capture_output=True,
            text=True,
            timeout=60,
        )
        return {
            "cmd": " ".join(args),
            "exit_code": proc.returncode,
            "stdout": proc.stdout.strip(),
            "stderr": proc.stderr.strip(),
            "ok": proc.returncode == 0,
        }

    add = _run(["add", "-A"])
    commit = _run(["commit", "-m", f"publish: {datetime.now(UTC).isoformat()}"])
    if not commit["ok"] and "nothing to commit" not in commit["stdout"] + commit["stderr"]:
        commit_ok = False
    else:
        commit_ok = True

    push = _run(["push"])
    return {
        "deployed": push["ok"],
        "add": add,
        "commit": {**commit, "ok": commit_ok},
        "push": push,
        "site_root": str(root),
    }
